-- TerraWatch — Phase 9.17: LinkedIn auto-poster — drafts queue.
--
-- The DataSnake LinkedIn company page posts 3× per week. Topics live in
-- docs/LINKEDIN_FEED.md (admin-maintained markdown). A new Edge Function
-- (generate-linkedin-post) reads the doc, picks the oldest unprocessed
-- topic by sha256 hash, asks Claude to draft a post, and writes a row
-- into linkedin_posts with status='draft'.
--
-- Admin reviews + approves via /admin/linkedin. Phase 9.17 ships the
-- generate+review loop only — manual copy to LinkedIn until Phase 9.17.1
-- adds the OAuth + UGC Posts API auto-publisher.
--
-- Mirrors blog_posts (migration 0019) + blog_generator_usage (0020).
-- Same is_admin() RLS pattern; same per-admin daily quota.

-- =====================================================================
-- 1. linkedin_posts — one row per generated draft
-- =====================================================================

create table if not exists public.linkedin_posts (
  id            uuid primary key default gen_random_uuid(),
  topic_hash    text not null unique,                        -- sha256 of the source line; prevents re-processing
  topic_text    text not null,                                -- the verbatim line from docs/LINKEDIN_FEED.md
  status        text not null
    check (status in ('draft','approved','scheduled','published','failed','rejected'))
    default 'draft',
  content       text not null,                                -- LinkedIn body, generated by Claude
  hashtags      text[] not null default '{}',
  scheduled_for timestamptz,                                  -- when 9.17.1 publish-cron should fire
  published_at  timestamptz,
  linkedin_urn  text,                                         -- urn:li:share:... returned by UGC API (9.17.1)
  publish_error text,                                         -- last failure reason (9.17.1)
  generated_by  uuid references auth.users on delete set null,
  approved_by   uuid references auth.users on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists linkedin_posts_status_idx
  on public.linkedin_posts (status, created_at desc);
create index if not exists linkedin_posts_scheduled_idx
  on public.linkedin_posts (scheduled_for asc)
  where status = 'approved';

alter table public.linkedin_posts enable row level security;

drop policy if exists "admin read linkedin_posts" on public.linkedin_posts;
create policy "admin read linkedin_posts"
  on public.linkedin_posts for select
  using (public.is_admin());

drop policy if exists "admin write linkedin_posts" on public.linkedin_posts;
create policy "admin write linkedin_posts"
  on public.linkedin_posts for all
  using (public.is_admin())
  with check (public.is_admin());

-- Auto-bump updated_at on any row change (same trigger shape as blog_posts).
create or replace function public.linkedin_posts_touch()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists linkedin_posts_touch on public.linkedin_posts;
create trigger linkedin_posts_touch
  before update on public.linkedin_posts
  for each row execute function public.linkedin_posts_touch();

comment on table public.linkedin_posts is
  'Phase 9.17 — auto-generated LinkedIn drafts queue. Admin reviews + approves in /admin/linkedin.';

-- =====================================================================
-- 2. linkedin_generator_usage — per-admin daily quota counter
-- =====================================================================

create table if not exists public.linkedin_generator_usage (
  user_id    uuid references auth.users on delete cascade,
  day        date not null,
  count      int not null default 0 check (count >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, day)
);

alter table public.linkedin_generator_usage enable row level security;

-- Admin can read their own usage row (UI displays remaining quota).
-- Service role bypasses RLS and does the increments inside the Edge Function.
drop policy if exists "admin read own linkedin usage" on public.linkedin_generator_usage;
create policy "admin read own linkedin usage"
  on public.linkedin_generator_usage for select
  using (auth.uid() = user_id and public.is_admin());

comment on table public.linkedin_generator_usage is
  'Phase 9.17 — per-admin daily generation counter. Default 5/day; env LINKEDIN_GEN_DAILY_LIMIT overrides.';
